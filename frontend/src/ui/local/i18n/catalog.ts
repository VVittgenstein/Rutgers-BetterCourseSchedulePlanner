export type LocalInterpolation = Readonly<Record<string, string | number>>;

export function localMessage(
  locale: SupportedLocale,
  key: LocalMessageKey,
  values: LocalInterpolation = {},
): string {
  const template = locale === 'zh-CN' ? localZhCNCatalog[key] : localEnUSCatalog[key];
  return template.replace(/\{\{([A-Za-z0-9_]+)\}\}/gu, (placeholder, name: string) =>
    Object.hasOwn(values, name) ? String(values[name]) : placeholder);
}
